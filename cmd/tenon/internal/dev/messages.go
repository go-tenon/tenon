// LocalesDir 是项目的翻译文件所在的目录。前端的界面文字是其中的 <前端>.<语言>.yaml，例如 web.zh-CN.yaml。
const LocalesDir = "locales"

// MessagesFile 是每个前端生成的界面文字目录，在前端的 src 目录中。
const MessagesFile = "messages.gen.ts"

// WriteMessages 为每个有界面文字的前端（locales 中有 <前端>.<语言>.yaml）生成 src/messages.gen.ts：每种语言的消息
// 和消息 ID 的类型，交给 @go-tenon/client 的 createI18n。返回生成时发现的问题，例如某种语言缺少别的语言中有的消息；
// 翻译文件写错时返回错误。没有界面文字的前端不生成。
func WriteMessages(root string, cfg *project.Config) ([]string, error) {
	var warnings []string
	for _, f := range cfg.Frontends {
		catalog, err := loadMessages(filepath.Join(root, LocalesDir), f.Name)
		if err != nil {
			return nil, err
		}
		if len(catalog) == 0 {
			continue
		}
		src, missing := messagesTS(f.Name, catalog)
		warnings = append(warnings, missing...)
		out := filepath.Join(root, f.Dir, "src", MessagesFile)
		if old, err := os.ReadFile(out); err == nil && bytes.Equal(old, src) {
			continue
		}
		if err := os.WriteFile(out, src, 0o644); err != nil {
			return nil, errors.Wrap(err, "write messages")
		}
	}
	return warnings, nil
}

// loadMessages 读取 dir 中前端 name 的翻译文件（<name>.<语言>.yaml 或 .yml），返回每种语言中每条消息：
// 只有 other 时是文字，有复数形式时是各形式的文字。目录不存在时返回空。
func loadMessages(dir, name string) (map[string]map[string]any, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, os.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, errors.Wrap(err, "read locales")
	}
	unmarshal := map[string]goi18n.UnmarshalFunc{"yaml": yaml.Unmarshal, "yml": yaml.Unmarshal}
	out := map[string]map[string]any{}
	for _, e := range entries {
		file := e.Name()
		ext := filepath.Ext(file)
		if e.IsDir() || (ext != ".yaml" && ext != ".yml") || !strings.HasPrefix(file, name+".") {
			continue
		}
		data, err := os.ReadFile(filepath.Join(dir, file))
		if err != nil {
			return nil, errors.Wrap(err, "read locales")
		}
		mf, err := goi18n.ParseMessageFileBytes(data, file, unmarshal)
		if err != nil {
			return nil, errors.Wrapf(err, "locales/%s", file)
		}
		tag := mf.Tag.String()
		if out[tag] == nil {
			out[tag] = map[string]any{}
		}
		for _, m := range mf.Messages {
			out[tag][m.ID] = messageValue(m)
		}
	}
	return out, nil
}

// messageValue 是一条消息在生成的目录中的值：只有 other 时是文字，否则是 { 形式: 文字 }，与 @go-tenon/client 的 Message 相同。
func messageValue(m *goi18n.Message) any {
	forms := map[string]string{}
	for form, text := range map[string]string{"zero": m.Zero, "one": m.One, "two": m.Two, "few": m.Few, "many": m.Many, "other": m.Other} {
		if text != "" {
			forms[form] = text
		}
	}
	if len(forms) == 1 && forms["other"] != "" {
		return m.Other
	}
	return forms
}

// messagesTS 生成前端 name 的 messages.gen.ts，并列出每种语言缺少的消息（别的语言中有、这种语言中没有的）。
func messagesTS(name string, catalog map[string]map[string]any) ([]byte, []string) {
	languages := make([]string, 0, len(catalog))
	ids := map[string]bool{}
	for l, msgs := range catalog {
		languages = append(languages, l)
		for id := range msgs {
			ids[id] = true
		}
	}
	sort.Strings(languages)
	all := make([]string, 0, len(ids))
	for id := range ids {
		all = append(all, id)
	}
	sort.Strings(all)

	var missing []string
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tenon generate. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "/** 前端 %s 的界面文字，来自 %s/%s.<语言>.yaml。交给 @go-tenon/client 的 createI18n。 */\n", name, LocalesDir, name)
	b.WriteString("export const messages = {\n")
	for _, l := range languages {
		fmt.Fprintf(&b, "  %s: {\n", quote(l))
		msgs := catalog[l]
		var absent []string
		for _, id := range all {
			v, ok := msgs[id]
			if !ok {
				absent = append(absent, id)
				continue
			}
			fmt.Fprintf(&b, "    %s: %s,\n", quote(id), jsonValue(v))
		}
		b.WriteString("  },\n")
		if len(absent) > 0 {
			missing = append(missing, fmt.Sprintf("%s/%s.%s.yaml is missing %d messages: %s", LocalesDir, name, l, len(absent), strings.Join(firstN(absent, 5), ", ")))
		}
	}
	b.WriteString("} as const\n\n")
	b.WriteString("/** 界面文字的消息 ID。 */\n")
	if len(all) == 0 {
		b.WriteString("export type MessageId = never\n")
	} else {
		b.WriteString("export type MessageId =\n")
		for _, id := range all {
			fmt.Fprintf(&b, "  | %s\n", quote(id))
		}
	}
	b.WriteString("\n// 登记消息 ID：@go-tenon/ui 的 useT 只接受其中的 ID。\n")
	b.WriteString("declare module \"@go-tenon/ui\" {\n  interface I18nRegister {\n    messageId: MessageId\n  }\n}\n")
	return []byte(b.String()), missing
}

// quote 返回 s 的 JSON 字符串，也是合法的 TypeScript 字符串。
func quote(s string) string {
	q, _ := json.Marshal(s)
	return string(q)
}

// jsonValue 返回消息的值：文字，或者按形式排好序的对象。
func jsonValue(v any) string {
	if s, ok := v.(string); ok {
		return quote(s)
	}
	forms := v.(map[string]string)
	keys := make([]string, 0, len(forms))
	for k := range forms {
		keys = append(keys, k)
	}
	order := []string{"zero", "one", "two", "few", "many", "other"}
	slices.SortFunc(keys, func(a, b string) int { return slices.Index(order, a) - slices.Index(order, b) })
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = k + ": " + quote(forms[k])
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

// firstN 返回 s 的前 n 项，多出的用“…”表示。
func firstN(s []string, n int) []string {
	if len(s) <= n {
		return s
	}
	return append(slices.Clone(s[:n]), "…")
}
